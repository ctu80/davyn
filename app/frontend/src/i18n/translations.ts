// `en` is intentionally empty: English is the source language, so an English
// string IS its own key and `translate()` falls back to the key verbatim. Only
// non-English locales need entries here.
const translations: Record<string, Dict> = { en: {}, de }

/**
 * Translate `key` for `locale`, falling back to the key itself (English source).
 * Optional `vars` replace `{name}` placeholders, e.g.
 *   translate('de', '{n} app passwords', { n: 3 }) → '3 App-Passwörter'
 */
export function translate(
  locale: string,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let out = translations[locale]?.[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return out
}
